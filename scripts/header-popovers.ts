import { chromium, expect } from "@playwright/test";
import { writeFile } from "node:fs/promises";
const browser = await chromium.launch({executablePath:"/usr/bin/google-chrome",headless:true,args:["--no-sandbox"]});
try {
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 await page.goto("http://127.0.0.1:4310");
 await page.getByLabel("Username",{exact:true}).fill("leader");
 await page.getByLabel("Password",{exact:true}).fill("OpenTask-Test-2026!");
 await page.getByRole("button",{name:"Sign in",exact:true}).click();
 await page.locator(".task-row").first().waitFor();
 const bell=page.locator('.notification-button');
 const count=await bell.innerText();
 await bell.click();
 const notices=page.locator('#notification-popover');
 await expect(notices).toBeVisible();
 await expect(notices.locator('.notice').first()).toBeVisible();
 await page.screenshot({path:'artifacts/header-notifications.png'});
 await notices.locator('.notice').first().click();
 await expect(notices).not.toBeVisible();
 await expect(page).toHaveURL(/task=/);
 await expect(bell).toHaveText(count);
 await page.getByRole('button',{name:'Account',exact:true}).click();
 const account=page.locator('#account-popover');
 await expect(account).toContainText('leader');
 await expect(account.getByRole('button',{name:'Sign out',exact:true})).toBeVisible();
 await page.screenshot({path:'artifacts/header-account.png'});
 await page.keyboard.press('Escape');
 await expect(account).not.toBeVisible();
 await page.getByRole('button',{name:'Account',exact:true}).click();
 await account.getByRole('button',{name:'Switch user',exact:true}).click();
 await expect(page.getByRole('button',{name:'Sign in',exact:true})).toBeVisible();
 await page.getByLabel('Username',{exact:true}).fill('member');
 await page.getByLabel('Password',{exact:true}).fill('OpenTask-Test-2026!');
 await page.getByRole('button',{name:'Sign in',exact:true}).click();
 await page.getByRole('button',{name:'Account',exact:true}).click();
 await expect(account).toContainText('member');
 await account.getByRole('button',{name:'Sign out',exact:true}).click();
 await expect(page.getByRole('button',{name:'Sign in',exact:true})).toBeVisible();
 await writeFile('artifacts/header-popovers.json',JSON.stringify({notifications:true,taskNavigation:true,countPreserved:true,accountInfo:true,escape:true,switchUser:true,logout:true}));
} finally {await browser.close();}
