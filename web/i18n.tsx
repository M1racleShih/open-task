export type Key = keyof typeof messages;
export type Lang = "en" | "zh";
export function translate(key: string, lang: Lang) {
  const normalized = key.startsWith("blocked:") ? "blocked" : key;
  return messages[normalized as Key]?.[lang === "en" ? 0 : 1] ?? normalized;
}
const Context = createContext<{
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: string) => string;
}>({ lang: "en", setLang: () => {}, t: (k) => k });
export function I18n({ children }: { children: ReactNode }) {
  const [lang, set] = useState<Lang>(() =>
    localStorage.getItem("open-task.language") === "zh" ? "zh" : "en",
  );
  useEffect(() => {
    document.documentElement.lang = lang === "en" ? "en" : "zh-CN";
  }, [lang]);
  const setLang = (l: Lang) => {
    localStorage.setItem("open-task.language", l);
    document.documentElement.lang = l === "en" ? "en" : "zh-CN";
    set(l);
  };
  return (
    <Context.Provider value={{ lang, setLang, t: (k) => translate(k, lang) }}>
      {children}
    </Context.Provider>
  );
}
export const useI18n = () => useContext(Context);
export const dateText = (date: string, lang: Lang) =>
  date && Number.isFinite(Date.parse(date))
    ? new Intl.DateTimeFormat(lang === "en" ? "en-GB" : "zh-CN", {
        dateStyle: "medium",
        timeStyle: "short",
        timeZone: "Asia/Shanghai",
      }).format(new Date(date))
    : "—";
